def strip_tags(s):
    return re.sub(r'<[^>]+>', '', s)


def unescape_basic(s):
    for a, b in [('&amp;', '&'), ('&mdash;', '—'), ('&ndash;', '–'),
                 ('&nbsp;', ' '), ('&quot;', '"'), ('&#39;', "'"),
                 ('&lt;', '<'), ('&gt;', '>')]:
        s = s.replace(a, b)
    return s


def esc_json(s):
    return (s.replace('\\', '\\\\').replace('"', '\\"')
             .replace('\n', ' ').replace('\r', ' '))


def get(pattern, html, default=''):
    m = re.search(pattern, html, re.S | re.I)
    return m.group(1).strip() if m else default


def extract_faqs(html):
    """Pull question/answer pairs out of the accordion markup.

    Questions and answers are collected separately and zipped in document
    order, rather than trying to match one balanced block with a regex.
    Nested divs make the block approach fail silently, which it did.
    """
    qs = [unescape_basic(strip_tags(q)).strip() for q in re.findall(
        r'<button class="acc-trigger"[^>]*>\s*<span>(.*?)</span>', html, re.S)]
    as_ = [unescape_basic(strip_tags(a)).strip() for a in re.findall(
        r'<div class="acc-panel"><div>(.*?)</div>\s*</div>', html, re.S)]
    if len(qs) != len(as_):
        print('    ! %d questions but %d answers — skipping FAQ schema' % (len(qs), len(as_)))
        return []
    return [(q, a) for q, a in zip(qs, as_) if q and a]



"""
Add the search and AI-citation layer to every page.

Run from inside tmfus-site. Idempotent: it removes anything it added
before re-adding, so running it twice is safe and re-running after a
content change refreshes the FAQ schema.

What it does per page:
  - canonical URL, in the CLEAN form (/sba-loans, not /sba-loans.html)
  - a robots directive that lets Google and the answer engines quote the
    page in full (max-snippet:-1) rather than truncating it at ~160 chars
  - hreflang, Open Graph and Twitter card tags
  - JSON-LD: Organization + WebSite on the home page, WebPage everywhere,
    BreadcrumbList off the home page, Service and LoanOrCredit on the
    product pages, HowTo on the application, FAQPage wherever the page
    has an accordion
  - rewrites internal links from foo.html to /foo so no click or crawl
    spends a 301

It also rewrites sitemap.xml from PAGES, so adding a page here is the
only thing you have to remember. Add it to .cpanel.yml too or it will
never reach the server.

Deliberately NOT done: no telephone or postal address is emitted in the
Organization schema, because none exists yet. Inventing one would be
worse than leaving it out — wrong NAP data actively harms local search.
"""


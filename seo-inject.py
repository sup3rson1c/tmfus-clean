def build_block(fname, path, html):
    title = unescape_basic(get(r'<title>(.*?)</title>', html))
    desc = unescape_basic(get(r'name="description" content="(.*?)"', html))
    url = SITE + (path or '/404')
    img = SITE + '/assets/logo-mark-512.png'

    indexable = path is not None

    tags = [
        BEGIN,
        '<link rel="canonical" href="%s">' % url,
        # max-snippet:-1 is the one that matters for AI answers: without it
        # Google caps the text an answer engine may quote from the page.
        '<meta name="robots" content="%s">' % (
            'index, follow, max-snippet:-1, max-image-preview:large, max-video-preview:-1'
            if indexable else 'noindex, follow'),
        '<link rel="alternate" hreflang="en-us" href="%s">' % url,
        '<link rel="alternate" hreflang="x-default" href="%s">' % url,
        '<meta property="og:type" content="%s">' % ('website' if fname == 'index.html' else 'article'),
        '<meta property="og:site_name" content="TMF Team">',
        '<meta property="og:title" content="%s">' % title,
        '<meta property="og:description" content="%s">' % desc,
        '<meta property="og:url" content="%s">' % url,
        '<meta property="og:image" content="%s">' % img,
        '<meta property="og:locale" content="en_US">',
        '<meta name="twitter:card" content="summary_large_image">',
        '<meta name="twitter:title" content="%s">' % title,
        '<meta name="twitter:description" content="%s">' % desc,
        '<meta name="twitter:image" content="%s">' % img,
    ]

    graph = []

    if fname == 'index.html':
        graph.append(ORGANISATION)
        graph.append('''{
      "@type": "WebSite",
      "@id": "%s/#website",
      "url": "%s/",
      "name": "TMF Team",
      "publisher": {"@id": "%s/#organization"},
      "inLanguage": "en-US"
    }''' % (SITE, SITE, SITE))

    page_type = {
        'about.html': 'AboutPage',
        'contact.html': 'ContactPage',
    }.get(fname, 'WebPage')

    crumb_ref = ''
    if path and path != '/':
        crumb_ref = ''',
      "breadcrumb": {"@id": "%s#breadcrumb"}''' % url

    graph.append('''{
      "@type": "%s",
      "@id": "%s#webpage",
      "url": "%s",
      "name": "%s",
      "description": "%s",
      "isPartOf": {"@id": "%s/#website"},
      "about": {"@id": "%s/#organization"},
      "datePublished": "%s",
      "dateModified": "%s",
      "inLanguage": "en-US"%s
    }''' % (page_type, url, url, esc_json(title), esc_json(desc), SITE, SITE,
            LAST_UPDATED, LAST_UPDATED, crumb_ref))

    # Breadcrumbs everywhere but the home page. Google draws these under
    # the result, and an answer engine uses them to work out where a page
    # sits in the site rather than guessing from the URL.
    if path and path != '/':
        graph.append('''{
      "@type": "BreadcrumbList",
      "@id": "%s#breadcrumb",
      "itemListElement": [
        {"@type": "ListItem", "position": 1, "name": "Home", "item": "%s/"},
        {"@type": "ListItem", "position": 2, "name": "%s", "item": "%s"}
      ]
    }''' % (url, SITE, esc_json(CRUMBS.get(path, strip_tags(title))), url))

    if fname in SERVICES:
        sname, sdesc = SERVICES[fname]
        graph.append('''{
      "@type": "Service",
      "name": "%s",
      "description": "%s",
      "provider": {"@id": "%s/#organization"},
      "areaServed": {"@type": "Country", "name": "United States"},
      "url": "%s"
    }''' % (esc_json(sname), esc_json(sdesc), SITE, url))

    if fname in LOAN_PRODUCTS:
        lp = LOAN_PRODUCTS[fname]
        graph.append('''{
      "@type": "%s",
      "@id": "%s#product",
      "name": "%s",
      "description": "%s",
      "provider": {"@id": "%s/#organization"},
      "areaServed": {"@type": "Country", "name": "United States"},
      "url": "%s",
      "amount": {
        "@type": "MonetaryAmount",
        "currency": "USD",
        "minValue": %d,
        "maxValue": %d
      }
    }''' % (lp['type'], url, esc_json(lp['name']), esc_json(lp['desc']),
            SITE, url, lp['min'], lp['max']))

    if fname in HOWTO:
        h = HOWTO[fname]
        supplies = ',\n        '.join(
            '{"@type": "HowToSupply", "name": "%s"}' % esc_json(x) for x in h['supply'])
        steps = ',\n        '.join(
            '''{
          "@type": "HowToStep",
          "position": %d,
          "name": "%s",
          "text": "%s",
          "url": "%s#step-%d"
        }''' % (i + 1, esc_json(n), esc_json(t), url, i + 1)
            for i, (n, t) in enumerate(h['steps']))
        graph.append('''{
      "@type": "HowTo",
      "@id": "%s#howto",
      "name": "%s",
      "description": "%s",
      "totalTime": "%s",
      "supply": [
        %s
      ],
      "step": [
        %s
      ]
    }''' % (url, esc_json(h['name']), esc_json(h['desc']), h['time'], supplies, steps))

    faqs = extract_faqs(html)
    if faqs:
        entities = ',\n        '.join(
            '''{
          "@type": "Question",
          "name": "%s",
          "acceptedAnswer": {"@type": "Answer", "text": "%s"}
        }''' % (esc_json(q), esc_json(a)) for q, a in faqs)
        graph.append('''{
      "@type": "FAQPage",
      "@id": "%s#faq",
      "mainEntity": [
        %s
      ]
    }''' % (url, entities))

    tags.append('<script type="application/ld+json">\n{\n  "@context": "https://schema.org",\n  "@graph": [\n    '
                + ',\n    '.join(graph) + '\n  ]\n}\n</script>')
    tags.append(END)
    return '\n'.join(tags), len(faqs)


def clean_links(html):
    """foo.html -> /foo, index.html -> /. Saves a 301 on every click."""
    def repl_with_hash(m):
        target, frag = m.group(1), (m.group(2) or '')
        if target == 'index.html':
            return 'href="/%s"' % frag
        return 'href="/%s%s"' % (target[:-5], frag)
    return re.sub(r'href="((?:index|about|contact|apply|funding-estimator|'
                  r'heloc-calculator|sba-loans|mca|terms|privacy|404)\.html)'
                  r'(#[A-Za-z0-9_-]+)?"',
                  lambda m: repl_with_hash(m), html)


def write_sitemap():
    """Rebuild sitemap.xml from PAGES.

    Generated rather than hand-kept, because a page that exists and is
    not in the sitemap is a page nobody finds, and that is exactly the
    sort of thing that gets forgotten when a page is added in a hurry.
    """
    entry = ('  <url>\n'
             '    <loc>%s%s</loc>\n'
             '    <lastmod>%s</lastmod>\n'
             '    <changefreq>%s</changefreq>\n'
             '    <priority>%s</priority>\n'
             '  </url>')
    rows = [
        entry % (SITE, path, LAST_UPDATED, freq, priority)
        for path, (priority, freq) in SITEMAP.items()
    ]
    xml = ('<?xml version="1.0" encoding="UTF-8"?>\n'
           '<!-- Generated by seo-inject.py. Edit PAGES and SITEMAP there, not here. -->\n'
           '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
           + '\n'.join(rows) + '\n</urlset>\n')
    io.open('sitemap.xml', 'w', encoding='utf-8').write(xml)
    print('%-24s %d urls' % ('sitemap.xml', len(rows)))


def main():
    total_faqs = 0
    for fname, path in PAGES.items():
        if not os.path.exists(fname):
            continue
        html = io.open(fname, encoding='utf-8').read()

        # remove a previous run
        html = re.sub(re.escape(BEGIN) + r'.*?' + re.escape(END) + r'\n?', '', html, flags=re.S)

        block, nfaq = build_block(fname, path, html)
        total_faqs += nfaq

        html = html.replace('</head>', block + '\n</head>', 1)
        html = clean_links(html)

        io.open(fname, 'w', encoding='utf-8').write(html)
        print('%-24s canonical %-24s faqs:%d' % (fname, path or '(noindex)', nfaq))

    write_sitemap()
    print('total FAQ entries in schema:', total_faqs)


if __name__ == '__main__':
    main()
